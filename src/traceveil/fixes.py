"""Fix plan for an audit report: what to change, where, which countries' laws each finding falls under, and how to check.

Data: `data/fixes/fix_templates.json` (the app's "How to fix" templates, core `FixCatalog`) and
`data/trackers/trackers.json` (tracker catalogue: entity -> sdkKey, company, company country), exact copies of
core/src/main/resources kept in sync by `tools/sync_law_data.py`. Templates are picked the way `FixCatalog.fixesFor`
picks them, and the country view comes from the LegalLens profiles (`laws`), so the CLI says what the app says.

The JSON plan is meant to be handed to a coding agent: every issue names its evidence, the fixes that resolve it and a
`doneWhen` test; every fix carries the manifest/code change, the steps, what to search for in the codebase and the
issues it resolves. `markdown()` renders the same plan as a task list. Nothing is generated by a model.
"""

from __future__ import annotations

import json
from functools import lru_cache
from importlib import resources

from . import laws
from .colors import PLAIN, Style

SCHEMA = "traceveil/fix-plan@1"
# FixCatalog.SDK_CHECKS: findings whose entities pick vendor SDK fixes.
SDK_CHECKS = {"C1", "C2", "C9", "C10", "C13"}
SEVERITY_RANK = {"CRITICAL": 0, "HIGH": 1, "MEDIUM": 2, "LOW": 3, "INFO": 4}
SDK_FILES = ["AndroidManifest.xml", "the Application subclass (onCreate)", "build.gradle / build.gradle.kts dependencies"]
UI_FILES = ["the consent / onboarding screen (layout or Compose code)", "string resources for the consent text"]
NO_TEMPLATE = ("No Traceveil template for this SDK yet. Initialise it only after the user accepts, keep it off after Reject "
               "or withdrawal, and look up the vendor's consent / opt-out API for your SDK version.")
AGENT_GUIDE = [
    "Work through `fixes` in order; each one lists the issues it resolves.",
    "Use `locate` to find the code: search the app's sources for the listed package prefixes and files.",
    "Apply `manifest` and `code` as shown; when `verified` is false, check the exact API for the SDK version in `docUrl`.",
    "Persist the user's consent choice and re-apply it on every launch; withdrawing must be as easy as giving consent.",
    "An issue is fixed when the `doneWhen` condition holds after re-running `verify.commands` on a debug build.",
    "Evidence is DNS lookups timed against consent choices: a lookup is an attempt to reach a host, not proof data was sent. "
    "This plan is a reading of the evidence, not a legal verdict.",
]


def _read(name: str):
    return json.loads(resources.files("traceveil").joinpath(f"data/{name}").read_text(encoding="utf-8"))


@lru_cache(maxsize=1)
def templates() -> tuple:
    return tuple(_read("fixes/fix_templates.json"))


@lru_cache(maxsize=1)
def trackers() -> dict:
    return {t["entity"]: t for t in _read("trackers/trackers.json")}


@lru_cache(maxsize=1)
def code_prefixes() -> dict:
    return {s["entity"]: s.get("prefixes", []) for s in _read("sdk_signatures.json")["signatures"]}


def place(view: dict) -> str:
    """Short country label of a lens: its one ISO code (IN, GB...), else the lens id (EU, US_CALIFORNIA...)."""
    regions = view.get("regions") or []
    return regions[0] if len(regions) == 1 else view["id"]


def _vendor(entity: str) -> dict:
    t = trackers().get(entity, {})
    return {"entity": entity, "company": t.get("company"), "category": t.get("category"),
            "companyCountry": (t.get("location") or {}).get("country"),
            "incorporatedIn": (t.get("incorporation") or {}).get("country"),
            "sdkKey": t.get("sdkKey"), "codePrefixes": code_prefixes().get(entity, [])}


def _jurisdictions(check: str, block: dict) -> list[dict]:
    pas = laws.passages()
    regions = {p["id"]: p.get("regions", []) for p in laws.load_profiles()}
    out = []
    for v in block["lenses"]:
        row = next((r for r in v["findings"] if r["check"] == check), None)
        if row is None:
            continue
        out.append({"lens": v["id"], "name": v["name"], "kind": v["kind"], "laws": v["laws"], "countries": regions.get(v["id"], []),
                    "relation": row["relation"], "note": row["note"],
                    "citations": [{"source": pas[r]["source"], "title": pas[r]["title"], "url": pas[r].get("url")}
                                  for r in row["refs"] if r in pas]})
    return out


def _fixes_for(finding: dict) -> list[dict]:
    """`FixCatalog.fixesFor` for one finding: vendor fixes for its entities, then the UI fixes for its check."""
    check = finding.get("check")
    by_id = {t["id"]: t for t in templates()}
    picked = []
    if check in SDK_CHECKS:
        for e in finding.get("entities", []):
            t = by_id.get(trackers().get(e, {}).get("sdkKey"))
            if t and check in t["appliesTo"] and t not in picked:
                picked.append(t)
    picked += [t for t in templates() if t["kind"] == "ui" and check in t["appliesTo"] and t not in picked]
    return picked


def build(report: dict, block: dict) -> dict:
    """The fix plan for `report`, with the country view from `block` (`laws.assess_all`, ideally over every lens)."""
    t = report.get("target", {})
    regions = {p["id"]: p.get("regions", []) for p in laws.load_profiles()}
    findings = [f for f in report.get("findings", []) if isinstance(f, dict)]
    actionable = sorted((f for f in findings if str(f.get("severity", "")).upper() != "INFO"),
                        key=lambda f: SEVERITY_RANK.get(str(f.get("severity", "")).upper(), 9))
    fixes: dict[str, dict] = {}
    issues = []
    for f in actionable:
        check = f.get("check")
        picked = _fixes_for(f)
        vendors = [_vendor(e) for e in f.get("entities", [])]
        for tpl in picked:
            fx = fixes.setdefault(tpl["id"], {**{k: tpl.get(k) for k in ("id", "kind", "title", "manifest", "code", "docUrl", "verified")},
                                              "steps": list(tpl.get("steps", [])), "resolves": [], "trackers": [],
                                              "locate": {"codePrefixes": [], "files": SDK_FILES if tpl["kind"] == "sdk" else UI_FILES}})
            fx["resolves"].append(check)
            for v in vendors:
                if v["sdkKey"] == tpl["id"] and v["entity"] not in fx["trackers"]:
                    fx["trackers"].append(v["entity"])
                    fx["locate"]["codePrefixes"] += [p for p in v["codePrefixes"] if p not in fx["locate"]["codePrefixes"]]
        juris = _jurisdictions(check, block)
        untemplated = [{"entity": v["entity"], "codePrefixes": v["codePrefixes"], "hint": NO_TEMPLATE}
                       for v in vendors if check in SDK_CHECKS and v["sdkKey"] not in [p["id"] for p in picked]]
        issues.append({
            "id": f"TV-{check}", "check": check, "severity": f.get("severity"), "evidenceType": f.get("evidenceType"),
            "title": f.get("title"), "plans": f.get("plans", []), "trackers": vendors,
            "requiredIn": [j["lens"] for j in juris if j["relation"] == "REQUIRED"],
            "contextIn": [j["lens"] for j in juris if j["relation"] == "CONTEXT"],
            "notApplicableIn": [j["lens"] for j in juris if j["relation"] == "NOT_APPLICABLE"],
            "jurisdictions": juris, "fixIds": [p["id"] for p in picked], "untemplatedTrackers": untemplated,
            "doneWhen": f"A fresh `traceveil audit` of {t.get('package', 'the app')} reports no {check} finding.",
        })
    pkg = t.get("package") or "<package>"
    return {
        "schema": SCHEMA, "source": "core FixCatalog + LegalLens (app resources)", "requestId": report.get("requestId"),
        "target": t, "score": report.get("score"), "band": report.get("band"),
        "agentInstructions": AGENT_GUIDE,
        "summary": {"issues": len(issues), "fixes": len(fixes), "verifiedFixes": sum(1 for x in fixes.values() if x["verified"]),
                    "byLens": [{"lens": v["id"], "name": v["name"], "countries": regions.get(v["id"], []), "score": v["score"], "band": v["band"],
                                "required": [i["id"] for i in issues if v["id"] in i["requiredIn"]]} for v in block["lenses"]]},
        "issues": issues,
        "fixes": list(fixes.values()),
        "notes": [{"check": f.get("check"), "title": f.get("title")} for f in findings if str(f.get("severity", "")).upper() == "INFO"],
        "verify": {"commands": [f"traceveil audit --package {pkg} --out traceveil-after.json",
                                "traceveil fix --report traceveil-after.json"],
                   "expect": "None of the issue checks above is reported again; the policy lens score rises."},
        "disclaimer": laws.DISCLAIMER,
    }


def _places(issue: dict, key: str, block_lenses: dict) -> list[str]:
    return [place(block_lenses[i]) if i in block_lenses else i for i in issue[key]]


def summary_lines(plan: dict, style: Style = PLAIN, compact: bool = False) -> list[str]:
    lens_by_id = {v["lens"]: {"id": v["lens"], "regions": v["countries"]} for v in plan["summary"]["byLens"]}
    fix_titles = {x["id"]: x["title"] for x in plan["fixes"]}
    lines = []
    for i in plan["issues"]:
        if not compact:
            lines.append(f"  {i['check']:<4} {style.severity(str(i['severity']), 8)} {i['title'] or ''}")
            if i["trackers"]:
                names = ", ".join(style.tracker(v["entity"]) + (style.dim(f" ({v['companyCountry']})") if v["companyCountry"] else "")
                                  for v in i["trackers"])
                lines.append(f"       {style.dim('trackers:')} {names}")
        req = ", ".join(_places(i, "requiredIn", lens_by_id))
        ctx = ", ".join(_places(i, "contextIn", lens_by_id))
        lines.append(f"       {style.dim('required in:')} {style.bad(req) if req else style.dim('none')}"
                     + (style.dim(f"   context: {ctx}") if ctx else ""))
        for fid in i["fixIds"]:
            lines.append(f"       {style.ok('fix:')} {fix_titles[fid]} {style.dim(f'[{fid}]')}")
        for u in i["untemplatedTrackers"]:
            lines.append(f"       {style.warn('fix:')} {u['entity']}: {style.dim('no template; gate its init behind consent')}")
    return lines


def summary(plan: dict, style: Style = PLAIN) -> str:
    t, s = plan["target"], plan["summary"]
    lines = [f"Traceveil fix plan  {style.bold(t.get('label', '?'))} ({t.get('package', '?')})  report {plan.get('requestId', '?')}  "
             f"score {style.score(plan['score'], plan['band'] or '')} / {style.band(plan['band'] or '?')}"]
    lines += summary_lines(plan, style)
    lines.append(style.bold("  By country") + style.dim("  (issues each law requires you to fix)"))
    for v in s["byLens"]:
        where = ", ".join(v["countries"]) if 0 < len(v["countries"]) <= 3 else f"{len(v['countries'])} countries" if v["countries"] else ""
        lines.append(f"    {v['lens']:<15} {style.score(v['score'], v['band'], 3)}  {style.band(v['band'], 12)} "
                     f"{', '.join(i.removeprefix('TV-') for i in v['required']) or style.dim('none')}" + (style.dim(f"  ({where})") if where else ""))
    lines.append(f"  {s['issues']} issue(s), {s['fixes']} fix(es), {s['verifiedFixes']} checked against vendor docs.")
    lines.append(style.dim("  For a coding agent: --json gives the report with these fixes in fixPlan; --format md prints them as Markdown"))
    return "\n".join(lines)


def markdown(plan: dict) -> str:
    """The plan as a Markdown task list a coding agent (or a person) can work through."""
    t = plan["target"]
    issues = {i["check"]: i for i in plan["issues"]}
    out = [f"# Traceveil fix plan: {t.get('label', '?')} (`{t.get('package', '?')}`)", "",
           f"Audit `{plan.get('requestId')}`, score **{plan['score']}** ({plan['band']}). "
           f"{plan['summary']['issues']} issue(s), {plan['summary']['fixes']} fix(es).", "",
           "## Instructions for the agent", ""]
    out += [f"- {g}" for g in plan["agentInstructions"]]
    out += ["", "## Tasks", ""]
    for n, fx in enumerate(plan["fixes"], 1):
        out.append(f"### {n}. [ ] {fx['title']} (`{fx['id']}`)")
        out.append("")
        res = ", ".join(f"{c} ({issues[c]['severity']})" for c in fx["resolves"] if c in issues)
        out.append(f"Resolves: {res}" + (f". Trackers: {', '.join(fx['trackers'])}" if fx["trackers"] else ""))
        loc = fx["locate"]
        out.append("")
        out.append("Where: " + "; ".join(loc["files"]) + (f". Search for imports of: {', '.join(f'`{p}`' for p in loc['codePrefixes'])}"
                                                          if loc["codePrefixes"] else ""))
        if not fx["verified"]:
            out += ["", "*Not checked against the vendor docs: confirm the exact API for your SDK version.*"]
        if fx.get("manifest"):
            out += ["", "AndroidManifest.xml:", "```xml", fx["manifest"], "```"]
        if fx.get("code"):
            out += ["", "```kotlin", fx["code"], "```"]
        if fx["steps"]:
            out += [""] + [f"- {s}" for s in fx["steps"]]
        if fx.get("docUrl"):
            out += ["", f"Docs: {fx['docUrl']}"]
        out.append("")
    extra = [(i, u) for i in plan["issues"] for u in i["untemplatedTrackers"]]
    if extra:
        out += [f"### {len(plan['fixes']) + 1}. [ ] Trackers without a template", ""]
        seen = set()
        for i, u in extra:
            if u["entity"] in seen:
                continue
            seen.add(u["entity"])
            pre = f" (imports: {', '.join(f'`{p}`' for p in u['codePrefixes'])})" if u["codePrefixes"] else ""
            out.append(f"- **{u['entity']}**{pre}: {u['hint']}")
        out.append("")
    out += ["## Issues and where they apply", ""]
    for i in plan["issues"]:
        out.append(f"### {i['id']} {i['severity']}: {i['title']}")
        out.append("")
        if i["trackers"]:
            out.append("Trackers: " + ", ".join(v["entity"] + (f" ({', '.join(x for x in (v['company'], v['companyCountry']) if x)})"
                                                           if v["company"] or v["companyCountry"] else "") for v in i["trackers"]))
        out.append(f"Seen in runs: {', '.join(i['plans']) or '-'}; evidence: {i['evidenceType']}. Fixed by: "
                   + (", ".join(f"`{x}`" for x in i["fixIds"]) or "see trackers without a template"))
        out += ["", "| Lens | Countries | Relation | Why |", "|---|---|---|---|"]
        for j in i["jurisdictions"]:
            where = ", ".join(j["countries"]) if len(j["countries"]) <= 3 else f"{len(j['countries'])} countries"
            note = (j["note"] or "").replace("|", "/")
            cites = " ".join(f"[{c['source']}]({c['url']})" if c.get("url") else c["source"] for c in j["citations"])
            out.append(f"| {j['name']} | {where or '-'} | {j['relation']} | {note}{' ' + cites if cites else ''} |")
        out += ["", f"Done when: {i['doneWhen']}", ""]
    out += ["## Verify", ""] + [f"```\n{c}\n```" for c in plan["verify"]["commands"]] + ["", plan["verify"]["expect"], "",
                                                                                        f"*{plan['disclaimer']}*", ""]
    return "\n".join(out)
