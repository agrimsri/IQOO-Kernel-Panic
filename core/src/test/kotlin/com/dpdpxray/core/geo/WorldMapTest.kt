package com.dpdpxray.core.geo

import com.dpdpxray.core.trackers.TrackerCatalog
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class WorldMapTest {
    private companion object {
        val bundled: WorldMap by lazy { WorldMap.loadDefault() }
        val svgText: String by lazy { WorldMap::class.java.getResourceAsStream("/geo/world.svg")!!.bufferedReader().use { it.readText() } }

        /** Every code the earlier outline could draw. The replacement must draw each of them, so no highlight is lost. */
        val PREVIOUS_CODES = (
            "AE AF AL AM AO AR AT AU AZ BA BD BE BF BG BI BJ BN BO BR BS BT BW BY BZ CA CD CF CG CH CI CL CM CN CO CR CU CY CZ " +
                "DE DJ DK DO DZ EC EE EG EH ER ES ET FK FI FJ FR GA GB GE GF GH GL GM GN GQ GR GT GW GY HN HR HT HU ID IE IL IN " +
                "IQ IR IS IT JM JO JP KE KG KH KP KR XK KW KZ LA LB LK LR LS LT LU LV LY MA MD ME MG MK ML MM MN MR MW MX MY MZ " +
                "NA NC NE NG NI NL NO NP NZ OM PA PE PG PH PL PK PR PS PT PY QA RO RS RU RW SA SB SD SE SI SJ SK SL SN SO SR SS " +
                "SV SY SZ TD TF TG TH TJ TL TM TN TR TT TW TZ UA UG US UY UZ VE VN VU YE ZA ZM ZW"
            ).split(" ").toSet()
    }

    @Test
    fun `parses ids, path data, size and the group offset from a small svg`() {
        val svg = """
            <svg width="100.5" height="50"><g transform="translate(0.25,0.5)">
              <path
                 d="m 1,1 2,2 z"
                 class="land" id="IN" />
              <path id="US" class="land"
                 d="M 5 5 L 9 9 Z"/>
              <path d="m 0,0 z" class="land"/>
            </g></svg>
        """.trimIndent()
        val m = WorldMap.parse(svg)
        assertEquals(100.5, m.width, 0.0)
        assertEquals(50.0, m.height, 0.0)
        assertEquals(0.25, m.offsetX, 0.0)
        assertEquals(0.5, m.offsetY, 0.0)
        assertEquals(setOf("IN", "US"), m.paths.keys)
        assertEquals("m 1,1 2,2 z", m.paths["IN"])
    }

    @Test
    fun `malformed or empty svg gives an empty map, not a crash`() {
        assertTrue(WorldMap.parse("").paths.isEmpty())
        assertTrue(WorldMap.parse("<svg><path d=\"\" id=\"IN\"/></svg>").paths.isEmpty())
        assertTrue(WorldMap.parse("<<<>>>").paths.isEmpty())
    }

    @Test
    fun `bundled outline is Natural Earth, public domain, generated by the committed converter`() {
        assertTrue(svgText.contains("Natural Earth 1:110m Admin 0 - Countries, v5.1.2 (public domain"))
        assertTrue(svgText.contains("tools/naturalearth_world_svg.py"))
        assertFalse(svgText.contains("amcharts", ignoreCase = true))
        assertTrue("size ${svgText.length}", svgText.length < 125_000)
    }

    @Test
    fun `bundled map draws every country the earlier outline drew, with ISO codes only`() {
        assertEquals(176, PREVIOUS_CODES.size)
        assertEquals(PREVIOUS_CODES, bundled.paths.keys)
        assertTrue(bundled.paths.keys.all { CountryNames.isIso(it) })
        listOf("IN", "US", "IE", "DE", "NL", "IL", "GB").forEach { assertNotNull(it, bundled.paths[it]) }
        assertEquals(1001.0, bundled.width, 0.0)
        assertEquals(644.44, bundled.height, 0.0)
        assertEquals(0.5, bundled.offsetX, 0.0)
        assertEquals(0.5, bundled.offsetY, 0.0)
    }

    @Test
    fun `every path is absolute-start relative-step data the canvas parser reads`() {
        val shape = Regex("(M-?[0-9.]+,-?[0-9.]+l(-?[0-9.]+,-?[0-9.]+ ?)+z)+")
        bundled.paths.forEach { (iso, d) -> assertTrue("$iso: ${d.take(60)}", shape.matches(d)) }
    }

    @Test
    fun `small countries without an outline are still nameable for the list view`() {
        assertNull(bundled.paths["SG"])
        assertEquals("Singapore", CountryNames.name("SG"))
        assertEquals("Kosovo", CountryNames.name("XK"))
        assertTrue(bundled.paths.containsKey("XK"))
    }

    @Test
    fun `a country with no drawing is reported as missing, not invented`() = assertNull(bundled.paths["XX"])

    @Test
    fun `highlighted countries with no outline are listed as not drawn, in name order`() {
        assertEquals(listOf("HK", "SG"), bundled.undrawn(setOf("SG", "IN", "HK", "US")))
        assertTrue(bundled.undrawn(setOf("IN", "US", "IE", "DE")).isEmpty())
        assertTrue(bundled.undrawn(emptySet()).isEmpty())
    }

    @Test
    fun `every ISO code the IP tables can place is either drawn or reported as not drawn`() {
        val all = java.util.Locale.getISOCountries().toSet() + "XK"
        val undrawn = bundled.undrawn(all).toSet()
        assertEquals(all, bundled.paths.keys.filter { it in all }.toSet() + undrawn)
        assertTrue(undrawn.none { it in bundled.paths })
        // Places DNS answers often land in that 1:110m geometry is too coarse to draw.
        assertTrue(undrawn.containsAll(listOf("SG", "HK", "BH", "MT", "MU")))
    }

    @Test
    fun `every owner country in the tracker catalogue has an outline`() {
        val owners = OwnerRegistry.fromCatalog(TrackerCatalog.loadDefault())
        val isos = TrackerCatalog.loadDefault().entries().mapNotNull { owners.find(it.entity)?.location?.iso }.toSet()
        assertTrue(isos.containsAll(setOf("US", "IL")))
        assertTrue(bundled.undrawn(isos).isEmpty())
    }
}
