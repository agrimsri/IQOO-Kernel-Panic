package com.dpdpxray.core.quarantine

import kotlinx.serialization.Serializable

/** What a blocked packet was trying to do, from its transport header only. */
@Serializable
enum class AttemptProtocol(val label: String) {
    /** TCP with SYN set and ACK clear: the first packet of a new connection. */
    TCP_SYN("TCP SYN"),

    /** Any other TCP packet, e.g. for a connection opened before quarantine started. */
    TCP_OTHER("TCP"),
    UDP("UDP"),

    /** ICMP (IPv4) or ICMPv6. */
    ICMP("ICMP"),
    OTHER("Other"),
}

/** Where a destination address points. Only [PUBLIC] and [PRIVATE] can be a server the app was built to reach. */
@Serializable
enum class AddressScope { PUBLIC, PRIVATE, LOOPBACK, LINK_LOCAL, MULTICAST, BROADCAST, UNSPECIFIED, RESERVED }

/**
 * Destination facts of one tunnel packet, read from the IP and transport headers only. Payload bytes are never read.
 * [destinationPort] is null for protocols without ports and for non-first fragments (no transport header present).
 */
data class PacketHeader(
    val ipVersion: Int,
    val destination: String,
    val scope: AddressScope,
    val protocolNumber: Int,
    val protocol: AttemptProtocol,
    val destinationPort: Int?,
    val icmpType: Int?,
    val fragment: Boolean,
    /** Generated by Android for the interface (IPv6 neighbour discovery, MLD, IGMP), not a connection by the app. */
    val networkControl: Boolean,
)

/**
 * Strictly bounded IPv4/IPv6 header reader for quarantine runs. Returns null for anything malformed or truncated:
 * every declared length must fit inside [length], and nothing past it is read. IPv6 extension headers are followed
 * (at most [MAX_EXTENSION_HEADERS]).
 */
object IpHeaders {
    const val MAX_EXTENSION_HEADERS = 8
    private const val ICMP = 1
    private const val IGMP = 2
    private const val TCP = 6
    private const val UDP = 17
    private const val ICMPV6 = 58
    private val ND_AND_MLD = setOf(130, 131, 132, 133, 134, 135, 136, 137, 143)

    fun parse(packet: ByteArray, length: Int = packet.size): PacketHeader? {
        if (length < 1 || length > packet.size) return null
        return when ((packet[0].toInt() and 0xf0) shr 4) {
            4 -> parseV4(packet, length)
            6 -> parseV6(packet, length)
            else -> null
        }
    }

    private fun parseV4(p: ByteArray, length: Int): PacketHeader? {
        if (length < 20) return null
        val ihl = (p[0].toInt() and 0x0f) * 4
        val total = u16(p, 2)
        if (ihl < 20 || total < ihl || total > length) return null
        val fragmentOffset = u16(p, 6) and 0x1fff
        val dst = p.copyOfRange(16, 20)
        return transport(4, dst, u8(p, 9), p, ihl, total, laterFragment = fragmentOffset != 0)
    }

    private fun parseV6(p: ByteArray, length: Int): PacketHeader? {
        if (length < 40) return null
        val end = 40 + u16(p, 4)
        if (end > length) return null
        val dst = p.copyOfRange(24, 40)
        var next = u8(p, 6)
        var off = 40
        var laterFragment = false
        var seen = 0
        while (next == 0 || next == 43 || next == 44 || next == 51 || next == 60) {
            if (++seen > MAX_EXTENSION_HEADERS) return null
            if (off + 8 > end) return null
            val headerLength = when (next) {
                44 -> {
                    if ((u16(p, off + 2) shr 3) != 0) laterFragment = true
                    8
                }
                51 -> (u8(p, off + 1) + 2) * 4 // authentication header counts 4-byte units
                else -> (u8(p, off + 1) + 1) * 8
            }
            if (off + headerLength > end) return null
            next = u8(p, off)
            off += headerLength
            if (laterFragment) break // the rest of the chain is in the first fragment
        }
        return transport(6, dst, next, p, off, end, laterFragment)
    }

    private fun transport(version: Int, dst: ByteArray, proto: Int, p: ByteArray, off: Int, end: Int, laterFragment: Boolean): PacketHeader? {
        val scope = IpAddresses.scope(dst)
        val address = IpAddresses.format(dst)
        fun header(protocol: AttemptProtocol, port: Int? = null, icmpType: Int? = null, control: Boolean = false) =
            PacketHeader(version, address, scope, proto, protocol, port, icmpType, laterFragment, control)

        val isIcmp = (version == 4 && proto == ICMP) || (version == 6 && proto == ICMPV6)
        if (laterFragment) {
            return header(
                when {
                    proto == TCP -> AttemptProtocol.TCP_OTHER
                    proto == UDP -> AttemptProtocol.UDP
                    isIcmp -> AttemptProtocol.ICMP
                    else -> AttemptProtocol.OTHER
                },
                control = proto == IGMP && version == 4,
            )
        }
        return when {
            proto == TCP -> {
                if (end - off < 20) return null
                val dataOffset = (u8(p, off + 12) shr 4) * 4
                if (dataOffset < 20 || off + dataOffset > end) return null
                val flags = u8(p, off + 13)
                val syn = flags and 0x02 != 0 && flags and 0x10 == 0
                header(if (syn) AttemptProtocol.TCP_SYN else AttemptProtocol.TCP_OTHER, port = u16(p, off + 2))
            }
            proto == UDP -> {
                if (end - off < 8) return null
                val udpLength = u16(p, off + 4)
                if (udpLength < 8 || off + udpLength > end) return null
                header(AttemptProtocol.UDP, port = u16(p, off + 2))
            }
            isIcmp -> {
                if (end - off < 4) return null
                val type = u8(p, off)
                header(AttemptProtocol.ICMP, icmpType = type, control = version == 6 && type in ND_AND_MLD)
            }
            else -> header(AttemptProtocol.OTHER, control = version == 4 && proto == IGMP)
        }
    }

    private fun u8(b: ByteArray, i: Int) = b[i].toInt() and 0xff
    private fun u16(b: ByteArray, i: Int) = (u8(b, i) shl 8) or u8(b, i + 1)
}

/** Text form and scope of raw IPv4 (4-byte) and IPv6 (16-byte) addresses, without any DNS or platform lookup. */
object IpAddresses {
    fun format(bytes: ByteArray): String = when (bytes.size) {
        4 -> bytes.joinToString(".") { (it.toInt() and 0xff).toString() }
        16 -> formatV6(bytes)
        else -> throw IllegalArgumentException("not an IP address: ${bytes.size} bytes")
    }

    /** RFC 5952: lowercase hex, no leading zeros, the longest (first, if tied) run of 2+ zero groups as "::". */
    private fun formatV6(b: ByteArray): String {
        val groups = IntArray(8) { ((b[2 * it].toInt() and 0xff) shl 8) or (b[2 * it + 1].toInt() and 0xff) }
        var bestStart = -1
        var bestLength = 1
        var i = 0
        while (i < 8) {
            if (groups[i] != 0) { i++; continue }
            val start = i
            while (i < 8 && groups[i] == 0) i++
            if (i - start > bestLength) { bestStart = start; bestLength = i - start }
        }
        if (bestStart < 0) return groups.joinToString(":") { it.toString(16) }
        val head = groups.take(bestStart).joinToString(":") { it.toString(16) }
        val tail = groups.drop(bestStart + bestLength).joinToString(":") { it.toString(16) }
        return "$head::$tail"
    }

    fun scope(bytes: ByteArray): AddressScope = when (bytes.size) {
        4 -> scopeV4(bytes, 0)
        16 -> scopeV6(bytes)
        else -> AddressScope.RESERVED
    }

    private fun scopeV4(b: ByteArray, at: Int): AddressScope {
        val a = b[at].toInt() and 0xff
        val c = b[at + 1].toInt() and 0xff
        val all = (0 until 4).map { b[at + it].toInt() and 0xff }
        return when {
            all.all { it == 255 } -> AddressScope.BROADCAST
            a == 0 -> AddressScope.UNSPECIFIED
            a == 127 -> AddressScope.LOOPBACK
            a == 10 || (a == 172 && c in 16..31) || (a == 192 && c == 168) || (a == 100 && c in 64..127) -> AddressScope.PRIVATE
            a == 169 && c == 254 -> AddressScope.LINK_LOCAL
            a in 224..239 -> AddressScope.MULTICAST
            a >= 240 -> AddressScope.RESERVED
            else -> AddressScope.PUBLIC
        }
    }

    private fun scopeV6(b: ByteArray): AddressScope {
        val first = b[0].toInt() and 0xff
        val second = b[1].toInt() and 0xff
        val zeroPrefix10 = (0 until 10).all { b[it].toInt() == 0 }
        return when {
            (0 until 16).all { b[it].toInt() == 0 } -> AddressScope.UNSPECIFIED
            (0 until 15).all { b[it].toInt() == 0 } && b[15].toInt() == 1 -> AddressScope.LOOPBACK
            zeroPrefix10 && (b[10].toInt() and 0xff) == 0xff && (b[11].toInt() and 0xff) == 0xff -> scopeV4(b, 12)
            first == 0xff -> AddressScope.MULTICAST
            first == 0xfe && (second and 0xc0) == 0x80 -> AddressScope.LINK_LOCAL
            (first and 0xfe) == 0xfc -> AddressScope.PRIVATE
            else -> AddressScope.PUBLIC
        }
    }
}
